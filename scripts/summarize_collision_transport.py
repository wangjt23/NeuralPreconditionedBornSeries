#!/usr/bin/env python3
"""Rebuild numerical tables and figures directly from factorization experiments."""

import argparse
import csv
import hashlib
import json
import statistics
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt


def read_rows(path):
    with path.open(newline="") as stream:
        return list(csv.DictReader(stream))


def summarize(rows, key):
    by_seed = {}
    for row in rows:
        by_seed.setdefault(row["seed"], []).append(float(row[key]))
    means = [statistics.mean(values) for values in by_seed.values()]
    return statistics.mean(means), statistics.stdev(means) if len(means) > 1 else 0.


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("runs", type=Path, nargs="+", help="Completed experiment directories")
    parser.add_argument("--output", type=Path, default=Path("docs/research/RTE_COLLISION_TRANSPORT_RESULTS.md"))
    args = parser.parse_args()
    text = ["# Collision/Transport Numerical Results", "",
            "Generated by `scripts/summarize_collision_transport.py`; no values are transcribed by hand.", "",
            "All losses are **mean squared relative physical residuals**. RMS is sqrt(loss), not the mean ratio. "
            "Train/validation/test losses describe the validation-selected checkpoint, not necessarily the last update. "
            "Iteration and solve-time summaries first average the three sources within each seed, then average seeds. "
            "The reported time variation is sample SD across seed means; it is not a confidence interval. "
            "Time excludes training and shared operator construction; each source time is the median of repeated warmed solves.", ""]
    for directory in args.runs:
        rows = read_rows(directory / "results.csv")
        settings = json.loads((directory / "settings.json").read_text())
        seeds = sorted({r["seed"] for r in rows})
        methods = list(dict.fromkeys(r["method"] for r in rows))
        heading = f"{settings['case']}, N={settings['size']}, L={settings['n_angles']}, learned depth={settings.get('depth', 2)}"
        text += [f"## {heading}", "", f"Data: `{directory}`. Seeds: {', '.join(seeds)}. "
                 f"Updates: {settings['steps']}; batch: {settings['batch_size']}; tolerance: {settings['tol']}; "
                 f"maximum iterations: {settings['solver_steps']}.", "",
                 "| Method | Train loss | Validation loss | Test loss | Source one-step ratio | Iters | Solve ms (SD) | Converged |",
                 "|---|---:|---:|---:|---:|---:|---:|---:|"]
        for method in methods:
            subset = [row for row in rows if row["method"] == method]
            losses = [summarize(subset, key)[0] for key in ("train_physical_loss", "validation_physical_loss",
                                                          "test_physical_loss", "source_one_step", "iters")]
            elapsed, deviation = summarize(subset, "seconds")
            successes = sum(float(row["final"]) <= settings["tol"] for row in subset)
            text.append(f"| {method} | " + " | ".join(f"{x:.6g}" for x in losses)
                        + f" | {1000*elapsed:.3f} ({1000*deviation:.3f}) | {successes}/{len(subset)} |")
        text += ["", "### Training And Selection", "",
                 "| Method | Parameters | Initial train loss | Last train loss | Last validation loss | Selected steps | Train+validation seconds/seed |",
                 "|---|---:|---:|---:|---:|---|---:|"]
        for method in methods:
            subset = [row for row in rows if row["method"] == method]
            if not subset[0].get("parameters") or method == "legacy_prepared":
                continue
            selected = [next(row["selected_step"] for row in subset if row["seed"] == seed) for seed in seeds]
            values = [summarize(subset, k)[0] for k in ("train_initial_loss", "train_last_loss", "validation_last_loss")]
            text.append(f"| {method} | {subset[0]['parameters']} | " + " | ".join(f"{x:.6g}" for x in values)
                        + f" | {', '.join(selected)} | {summarize(subset, 'training_seconds')[0]:.3f} |")

        strong_hss = "HSS4_sequence" if "HSS4_sequence" in methods else "HSS4_tuned"
        extra = "learned_global_modes" if "learned_global_modes" in methods else "HSS2_tuned"
        display = [m for m in ("TSA4", strong_hss, extra, "learned_modes", "legacy_prepared") if m in methods]
        fig, axes = plt.subplots(1, 2, figsize=(11, 4.3), layout="constrained")
        means = [1000*summarize([r for r in rows if r["method"] == m], "seconds")[0] for m in display]
        errors = [1000*summarize([r for r in rows if r["method"] == m], "seconds")[1] for m in display]
        palette = ["#656565", "#13806f", "#377eb8", "#b83758", "#805ba5"]
        axes[0].barh(display, means, xerr=errors, color=palette[:len(display)], capsize=3)
        axes[0].set_xlabel("Warmed solve time (ms); SD across seeds")
        axes[0].set_title("True residual tolerance " + str(settings["tol"]))
        axes[0].invert_yaxis()
        history_rows = read_rows(directory / "convergence.csv")
        for m, color in zip(display, palette):
            subset = [r for r in history_rows if r["method"] == m]
            curves = {}
            for r in subset:
                curves.setdefault((r["seed"], r["test_source"]), {})[int(r["iteration"])] = float(r["true_residual"])
            final_iteration = max(max(curve) for curve in curves.values())
            values = [statistics.mean(curve.get(i, curve[max(curve)]) for curve in curves.values())
                      for i in range(final_iteration + 1)]
            axes[1].semilogy(range(final_iteration + 1), values, color=color, label=m)
        axes[1].set_xlabel("FGMRES iteration")
        axes[1].set_ylabel("Mean true relative residual")
        axes[1].set_title("Stopped histories padded with final residual")
        axes[1].legend(fontsize=8)
        axes[1].grid(alpha=.2)
        fig.suptitle(heading)
        figure = directory / "comparison.png"
        fig.savefig(figure, dpi=160)
        plt.close(fig)
        relative = Path("../..") / figure
        text += ["", f"![Convergence and solve time]({relative.as_posix()})", "", "### Artifact Hashes", ""]
        for name in ("results.csv", "bank_groups.csv", "classical_tuning.csv", "convergence.csv", "settings.json"):
            digest = hashlib.sha256((directory / name).read_bytes()).hexdigest()
            text.append(f"- `{name}`: `{digest}`")
        text.append("")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(text) + "\n")
    print(args.output)


if __name__ == "__main__":
    main()
