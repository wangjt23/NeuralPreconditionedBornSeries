#!/usr/bin/env python3
"""Conservatively archive unreferenced RTE scratch artifacts; dry-run by default."""

import argparse
import csv
from dataclasses import dataclass
import hashlib
import io
import os
from pathlib import Path
import posixpath
import re
import stat
import subprocess
import sys
import tempfile
from urllib.parse import unquote


ARCHIVE = Path("rte/archive")
SMOKE = ARCHIVE / "smoke"
INVENTORY = ARCHIVE / "artifact_inventory.tsv"
INDEX = ARCHIVE / "ARTIFACT_INDEX.md"
GENERATED = {INVENTORY, INDEX}
ALLOWED_SUFFIXES = {".csv", ".tsv", ".md", ".tex", ".txt"}
IGNORED_REFERENCE_SUFFIXES = {
    ".json", ".jsonl", ".yaml", ".yml", ".toml", ".ini", ".cfg",
    ".py", ".sh", ".md", ".rst", ".txt", ".tex", ".bib", ".ipynb",
}
CACHE_PARTS = {".git", "__pycache__", ".venv", "venv", "node_modules"}
GROUPS = ("notes", "results", "traces", "core code", "scratch")
MOVE_FIELDS = ("source", "destination", "bytes", "sha256")
INVENTORY_FIELDS = ("group", "path", "bytes", "sha256")
INDEX_MARKER = "<!-- Generated by scripts/organize_research_artifacts.py -->"


@dataclass(frozen=True)
class Move:
    source: str
    destination: str
    size: int
    sha256: str

    def row(self):
        return (self.source, self.destination, self.size, self.sha256)


def git_paths(root, *args):
    result = subprocess.run(
        ["git", "-C", str(root), "ls-files", "-z", *args],
        check=True, stdout=subprocess.PIPE,
    )
    return {Path(os.fsdecode(p)) for p in result.stdout.split(b"\0") if p}


def safe_path(root, relative):
    """Reject symlinks, including symlinked parents, before reading or writing."""
    relative = Path(relative)
    if relative.is_absolute() or ".." in relative.parts:
        raise ValueError(f"Unsafe relative path: {relative}")
    current = root
    for part in relative.parts:
        current = current / part
        if current.is_symlink():
            raise ValueError(f"Refusing symlink: {current}")
    return current


def project_paths(root):
    paths = git_paths(root, "--cached", "--others", "--exclude-standard")
    return sorted(p for p in paths if os.path.lexists(root / p))


def hash_file(path):
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def fingerprint(root, path):
    absolute = safe_path(root, path)
    before = absolute.stat()
    if not stat.S_ISREG(before.st_mode):
        raise ValueError(f"Not a regular file: {path}")
    digest = hash_file(absolute)
    after = absolute.stat()
    if (before.st_ino, before.st_size, before.st_mtime_ns) != (
        after.st_ino, after.st_size, after.st_mtime_ns
    ):
        raise ValueError(f"File changed while hashing: {path}")
    return after.st_size, digest


def is_candidate(path):
    return (
        path.parent == Path("rte")
        and path.name.startswith(("tmp_", "TMP_"))
        and path.suffix.lower() in ALLOWED_SUFFIXES
    )


def is_generated(path):
    return path in GENERATED or (
        path.parent == ARCHIVE and path.match("smoke_moves_*.tsv")
    )


def find_references(root, candidates, paths):
    """Conservative case-insensitive stem matches, including self references."""
    references = {p: [] for p in candidates}
    by_stem = {}
    for path in candidates:
        by_stem.setdefault(path.stem.lower(), []).append(path)
    if not by_stem:
        return references
    pattern = re.compile("|".join(re.escape(s) for s in sorted(by_stem, key=len, reverse=True)))
    ignored = git_paths(root, "--others", "--ignored", "--exclude-standard")
    extra = {
        p for p in ignored
        if p.suffix.lower() in IGNORED_REFERENCE_SUFFIXES
        and not CACHE_PARTS.intersection(p.parts)
    }
    for path in sorted(set(paths) | extra):
        if is_generated(path):
            continue
        absolute = safe_path(root, path)
        if not absolute.is_file():
            raise ValueError(f"Cannot scan reference source: {path}")
        # Also catch URL-escaped names and LaTeX-escaped underscores.
        content = unquote(absolute.read_bytes().decode("utf-8", errors="replace"))
        for number, line in enumerate(content.lower().replace("\\_", "_").splitlines(), 1):
            for match in pattern.finditer(line):
                # A short stem may be a prefix of the matched longer stem.
                for stem, targets in by_stem.items():
                    if stem in match.group():
                        for target in targets:
                            hit = f"{path.as_posix()}:{number}"
                            if hit not in references[target]:
                                references[target].append(hit)
    return references


def make_plan(root):
    paths = project_paths(root)
    candidates = [p for p in paths if is_candidate(p)]
    references = find_references(root, candidates, paths)
    moves = []
    for path in candidates:
        safe_path(root, path)
        if references[path]:
            continue
        destination = SMOKE / path.name
        if os.path.lexists(safe_path(root, destination)):
            raise ValueError(f"Destination already exists (no clobber): {destination}")
        size, digest = fingerprint(root, path)
        moves.append(Move(path.as_posix(), destination.as_posix(), size, digest))
    return moves, references


def tsv(fields, rows):
    output = io.StringIO(newline="")
    writer = csv.writer(output, delimiter="\t", lineterminator="\n")
    writer.writerow(fields)
    writer.writerows(rows)
    return output.getvalue()


def manifest_moves(root):
    directory = safe_path(root, ARCHIVE)
    moves = []
    sources, destinations = set(), set()
    for path in sorted(directory.glob("smoke_moves_*.tsv")):
        safe_path(root, path.relative_to(root))
        with path.open(newline="", encoding="utf-8") as handle:
            reader = csv.DictReader(handle, delimiter="\t")
            if reader.fieldnames != list(MOVE_FIELDS):
                raise ValueError(f"Invalid manifest header: {path}")
            for row in reader:
                move = Move(row["source"], row["destination"], int(row["bytes"]), row["sha256"])
                source, destination = Path(move.source), Path(move.destination)
                if not is_candidate(source) or destination != SMOKE / source.name:
                    raise ValueError(f"Out-of-scope manifest row: {row}")
                if move.size < 0 or not re.fullmatch(r"[0-9a-f]{64}", move.sha256):
                    raise ValueError(f"Invalid manifest fingerprint: {row}")
                if source in sources or destination in destinations:
                    raise ValueError(f"Duplicate manifest mapping: {source}")
                sources.add(source)
                destinations.add(destination)
                moves.append(move)
    return moves


def verify_archive(root):
    moves = manifest_moves(root)
    for move in moves:
        if os.path.lexists(safe_path(root, move.source)):
            raise ValueError(f"Original path still exists or was recreated: {move.source}")
        if fingerprint(root, move.destination) != (move.size, move.sha256):
            raise ValueError(f"Archived content differs: {move.destination}")
    return moves


def ensure_fingerprint(root, path, move):
    if fingerprint(root, path) != (move.size, move.sha256):
        raise ValueError(f"Content changed since plan: {path}")


def apply_moves(root, moves):
    if not moves:
        return None
    # Re-scan immediately before touching paths; newly added references cancel the run.
    fresh_moves, _ = make_plan(root)
    if moves != fresh_moves:
        raise ValueError("Plan changed; rerun the dry-run before applying")
    content = tsv(MOVE_FIELDS, (m.row() for m in moves))
    batch = hashlib.sha256(content.encode("utf-8")).hexdigest()[:16]
    manifest = ARCHIVE / f"smoke_moves_{batch}.tsv"
    if os.path.lexists(safe_path(root, manifest)):
        raise ValueError(f"Manifest already exists: {manifest}")
    archive = safe_path(root, SMOKE)
    archive.mkdir(parents=True, exist_ok=True)
    for move in moves:
        ensure_fingerprint(root, move.source, move)
        if os.path.lexists(safe_path(root, move.destination)):
            raise ValueError(f"Destination already exists: {move.destination}")
        if (root / move.source).stat().st_dev != archive.stat().st_dev:
            raise ValueError("Archive must be on the same filesystem as the source")
    # link() fails on any existing destination. Keep EVERY source until all links
    # and the durable manifest exist. Interruption never discards the last copy.
    for move in moves:
        os.link(safe_path(root, move.source), safe_path(root, move.destination))
    for move in moves:
        ensure_fingerprint(root, move.source, move)
        ensure_fingerprint(root, move.destination, move)
    with safe_path(root, manifest).open("x", encoding="utf-8", newline="") as handle:
        handle.write(content)
        handle.flush()
        os.fsync(handle.fileno())
    for move in moves:
        source = safe_path(root, move.source)
        destination = safe_path(root, move.destination)
        ensure_fingerprint(root, move.source, move)
        ensure_fingerprint(root, move.destination, move)
        if not os.path.samefile(source, destination):
            raise ValueError(f"Source/archive identity changed: {move.source}")
        source.unlink()
    verify_archive(root)
    return manifest


def group_for(path):
    name = path.name.lower()
    suffix = path.suffix.lower()
    if SMOKE in path.parents or name.startswith("tmp_") or suffix in {
        ".aux", ".fls", ".fdb_latexmk", ".log", ".out", ".toc", ".synctex",
    }:
        return "scratch"
    if "_history" in name or "_trace" in name or suffix in {".jsonl", ".sqlite3"}:
        return "traces"
    if suffix in {".csv", ".tsv", ".mat", ".npz", ".npy", ".pt", ".pth"} or name.endswith("_results_table.tex"):
        return "results"
    if suffix in {".py", ".sh", ".ipynb", ".yaml", ".yml", ".toml", ".json", ".cfg", ".ini"}:
        return "core code"
    return "notes"


def inventory_text(root):
    rows = []
    for path in project_paths(root):
        if path in GENERATED:
            continue
        size, digest = fingerprint(root, path)
        rows.append((group_for(path), path.as_posix(), size, digest))
    rows.sort(key=lambda row: (GROUPS.index(row[0]), row[1]))
    table = tsv(INVENTORY_FIELDS, rows)
    index = [
        INDEX_MARKER, "# Project Artifact Index", "",
        "Repository-wide, deterministic inventory of existing tracked files plus",
        "non-ignored untracked files. Ignored untracked generated files are excluded;",
        "tracked files remain included even if an ignore rule matches them.",
        "The two generated inventory files exclude themselves to avoid recursive hashes.",
        "Groups are filename-based navigation aids, not scientific validation labels.",
        "Archive manifests are organizational metadata in the results group.", "",
        "Regenerate from the repository root:", "", "```sh",
        "python3 scripts/organize_research_artifacts.py --inventory-only --apply",
        "python3 scripts/organize_research_artifacts.py --verify", "```", "",
        "[SHA-256 inventory](artifact_inventory.tsv) | [Archive policy](README.md)", "",
        "| Group | Files | Bytes |", "| --- | ---: | ---: |",
    ]
    for group in GROUPS:
        selected = [row for row in rows if row[0] == group]
        index.append(f"| {group} | {len(selected)} | {sum(row[2] for row in selected)} |")
    for group in GROUPS:
        index.extend(["", f"## {group.title()}", ""])
        for _, path, size, _ in (row for row in rows if row[0] == group):
            target = posixpath.relpath(path, ARCHIVE.as_posix())
            label = path.replace("[", "\\[").replace("]", "\\]")
            index.append(f"- [{label}](<{target}>) ({size} bytes)")
    return table, "\n".join(index) + "\n"


def validate_generated_target(root, relative, marker):
    path = safe_path(root, relative)
    if path.exists() and not path.read_text(encoding="utf-8").startswith(marker):
        raise ValueError(f"Refusing to overwrite a non-generated file: {relative}")
    return path


def write_generated(root, relative, content, marker):
    path = validate_generated_target(root, relative, marker)
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", newline="", dir=path.parent, delete=False) as handle:
        temporary = Path(handle.name)
        handle.write(content)
        handle.flush()
        os.fsync(handle.fileno())
    try:
        validate_generated_target(root, relative, marker)
        if path.exists():
            os.replace(temporary, path)
        else:
            os.link(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    action = parser.add_mutually_exclusive_group()
    action.add_argument("--apply", action="store_true", help="Apply moves and write the inventory")
    action.add_argument("--dry-run", action="store_true", help="Read-only preview (the default)")
    action.add_argument("--verify", action="store_true", help="Read-only check of manifests and inventory")
    parser.add_argument("--inventory-only", action="store_true", help="Do not plan or perform moves")
    args = parser.parse_args(argv)
    root = args.root.resolve()
    try:
        actual = subprocess.check_output(["git", "-C", str(root), "rev-parse", "--show-toplevel"], text=True).strip()
        if Path(actual).resolve() != root:
            raise ValueError("--root must be the Git repository root")
        archived = verify_archive(root)
        if args.verify:
            expected = inventory_text(root)
            for relative, content in zip((INVENTORY, INDEX), expected):
                path = safe_path(root, relative)
                if not path.exists() or path.read_text(encoding="utf-8") != content:
                    raise ValueError(f"Inventory missing or stale: {relative}")
            print(f"VERIFIED: {len(archived)} archived files, {sum(m.size for m in archived)} bytes; hashes, absent original paths, and inventory match")
            return 0
        moves, references = ([], {}) if args.inventory_only else make_plan(root)
        print("APPLY" if args.apply else "DRY RUN (no filesystem changes)")
        for path, hits in references.items():
            if hits:
                print(f"KEEP\t{path}\t" + "; ".join(hits))
        for move in moves:
            print(f"MOVE\t{move.source}\t{move.destination}\t{move.size}\t{move.sha256}")
        print(f"Planned moves: {len(moves)}; bytes: {sum(m.size for m in moves)}; referenced candidates retained: {sum(bool(h) for h in references.values())}")
        if not args.apply:
            print(f"Would refresh {INVENTORY} and {INDEX}; use --apply to write")
            return 0
        validate_generated_target(root, INVENTORY, "\t".join(INVENTORY_FIELDS) + "\n")
        validate_generated_target(root, INDEX, INDEX_MARKER + "\n")
        manifest = apply_moves(root, moves)
        table, index = inventory_text(root)
        write_generated(root, INVENTORY, table, "\t".join(INVENTORY_FIELDS) + "\n")
        write_generated(root, INDEX, index, INDEX_MARKER + "\n")
        archived = verify_archive(root)
        print(f"APPLIED: {len(moves)} moves; verified {len(archived)} cumulative archived files")
        if manifest:
            print(f"Manifest: {manifest}")
        return 0
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        print(f"ERROR: {error}. No automatic rollback or data deletion is attempted.", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
