"""Classical full-spatial range of the unshifted homogeneous transport solve.

U(k)=H0(k)^-1 Q uses the supplied original FP64 physical RTE's actual stored
streaming symbol, phase, quadrature and float64 material means. Q contains
angular-index Fourier columns (0,+1,-1), the existing harmonic convention;
physical directions are never replaced by ideal directions. Higher angular
harmonics generated by the full L-angle solve remain in U. No spatial modes
are dropped, including even-grid Nyquist modes.

The homogeneous response itself already exists as
reference_transport_solve(rhs,harmonics=1) with an unshifted matching mean
reference. This isolated class exposes its range and exact heterogeneous
image/adjoints as a classical control, not a learned or novel homogeneous
preconditioner. A reduced solve does not establish full physical convergence.
"""

import math

import torch


class TransportResponseRange:
    """Fixed-material U and B=H U, accepting complex128 fields only.

    Coefficients are (B,M,H,W); full-angle fields are (B,L,H,W). A material
    batch of one may serve multiple RHS. Other material batches must match
    the field batch. Inputs and derived caches are frozen: replacements,
    in-place mutations or layout/settings changes require reconstruction.
    prepare() validates this state; it never silently refreshes a cache.

    The retained full-spatial response is (B_material,H,W,L,M), 36MiB at
    B=1,N256,L12,M3 in complex128. Construction solves LxL systems for M
    RHS once. Neither a full inverse nor a full LxL symbol is retained.
    """

    _PHYSICAL_TENSORS = (
        "sigma_t", "sigma_s", "directions", "phase_matrix", "weights", "kx", "ky",
    )
    _PHYSICAL_SETTINGS = (
        "shape", "dx", "n_angles", "float_dtype", "complex_dtype",
        "anisotropy_g", "setup_generation",
    )
    _CACHES = ("basis", "gram", "mean_t", "mean_s", "response_symbol")

    @torch.no_grad()
    def __init__(self, high, modes=(0, 1, -1)):
        self.physical = high
        self.high = high
        self.modes = tuple(modes)
        if not self.modes or any(type(mode) is not int for mode in self.modes):
            raise ValueError("angular modes must be a nonempty sequence of integers")
        if len({mode % high.n_angles for mode in self.modes}) != len(self.modes):
            raise ValueError("angular modes must be distinct modulo n_angles")
        self.n_modes = len(self.modes)
        self._validate_initial()
        op, device = self.physical, high.sigma_t.device
        angles = 2 * math.pi * torch.arange(op.n_angles, dtype=torch.float64, device=device) / op.n_angles
        mode_tensor = torch.tensor(self.modes, dtype=torch.float64, device=device)
        self.basis = torch.exp(1j * angles[:, None] * mode_tensor[None, :]) / math.sqrt(op.n_angles)
        self.gram = self.basis.conj().T @ self.basis
        self.mean_t = op.sigma_t.mean((-2, -1), keepdim=True)
        self.mean_s = op.sigma_s.mean((-2, -1), keepdim=True)
        matrix = self._homogeneous_matrix_unchecked()
        rhs = self.basis.reshape(1, 1, 1, op.n_angles, self.n_modes).expand(
            op.sigma_t.shape[0], *op.shape, op.n_angles, self.n_modes,
        )
        self.response_symbol = torch.linalg.solve(matrix, rhs)
        if not bool(torch.isfinite(self.response_symbol).all()):
            raise ValueError("homogeneous transport response is not finite")
        # Retain external objects as well as metadata. An allocator cannot
        # recycle captured coefficient/cache storage when an owner replaces it.
        self._captured_operator = op
        self._captured_physical_tensors = tuple(getattr(op, name) for name in self._PHYSICAL_TENSORS)
        self._captured_caches = tuple(getattr(self, name) for name in self._CACHES)
        self.cached_signature = self._signature()

    def _validate_initial(self):
        op = self.physical
        if op.float_dtype != torch.float64 or op.complex_dtype != torch.complex128:
            raise ValueError("supply the actual promoted or native FP64 physical RTE")
        if any(not hasattr(op, name) for name in self._PHYSICAL_TENSORS):
            raise ValueError("physical material setup is required")
        inputs = tuple(getattr(op, name) for name in self._PHYSICAL_TENSORS)
        if any(value.dtype != torch.float64 for value in inputs):
            raise ValueError("physical coefficient and geometry buffers must all be float64")
        if any(value.device != op.sigma_t.device for value in inputs):
            raise ValueError("physical coefficient/geometry devices differ")
        if any(not bool(torch.isfinite(value).all()) for value in inputs):
            raise ValueError("physical coefficients and geometry must be finite")
        if (op.sigma_t.ndim != 4 or op.sigma_t.shape[1] != 1
                or op.sigma_t.shape != op.sigma_s.shape
                or tuple(op.sigma_t.shape[-2:]) != tuple(op.shape)
                or op.sigma_t.shape[0] < 1):
            raise ValueError("material must have shape (B,1,physical H,physical W)")
        if (tuple(op.directions.shape) != (op.n_angles, 2)
                or tuple(op.weights.shape) != (op.n_angles,)
                or tuple(op.phase_matrix.shape) != (op.n_angles, op.n_angles)):
            raise ValueError("stored angular geometry/quadrature shapes differ")

    @staticmethod
    def _tensor_signature(value):
        return (id(value), value.data_ptr(), value._version, value.dtype, value.device,
                tuple(value.shape), tuple(value.stride()), value.storage_offset())

    def _signature(self):
        op = self.physical
        physical = tuple(self._tensor_signature(getattr(op, name)) for name in self._PHYSICAL_TENSORS)
        caches = tuple(self._tensor_signature(getattr(self, name)) for name in self._CACHES)
        settings = tuple((name, getattr(op, name, None)) for name in self._PHYSICAL_SETTINGS)
        return (id(op), id(self.high), settings, self.modes, self.n_modes, physical, caches)

    def prepare(self):
        """Validate frozen inputs/caches; changed state requires reconstruction."""
        try:
            current = self._signature()
        except (AttributeError, TypeError) as error:
            raise RuntimeError("physical operator or response cache changed; reconstruct") from error
        if current != self.cached_signature:
            raise RuntimeError("physical operator or response cache changed; reconstruct")
        return self

    def _validate_field(self, value, channels):
        self.prepare()
        op = self.physical
        if value.dtype != torch.complex128:
            raise ValueError("transport-response fields must be complex128")
        if value.ndim != 4 or value.shape[1] != channels or tuple(value.shape[-2:]) != tuple(op.shape):
            raise ValueError("field must have shape (B,channels,physical H,physical W)")
        if value.device != op.sigma_t.device:
            raise ValueError("field and physical material devices differ")
        if value.shape[0] < 1 or (op.sigma_t.shape[0] != 1 and value.shape[0] != op.sigma_t.shape[0]):
            raise ValueError("field batch must equal material batch unless material batch is one")

    @staticmethod
    def _angular(matrix, value):
        return torch.einsum("ij,bjhw->bihw", matrix, value)

    @staticmethod
    def _spectral(matrix, value):
        spectrum = torch.fft.fftn(value, dim=(-2, -1), norm="backward")
        result = torch.einsum("bhwij,bjhw->bihw", matrix, spectrum)
        return torch.fft.ifftn(result, dim=(-2, -1), norm="backward")

    def _homogeneous_matrix_unchecked(self):
        op, device = self.physical, self.physical.sigma_t.device
        batch = op.sigma_t.shape[0]
        stream = op._stream_symbol(batch, torch.complex128, device)
        diagonal = torch.diag_embed(stream.permute(0, 2, 3, 1))
        eye = torch.eye(op.n_angles, dtype=torch.complex128, device=device)
        # Weight the INPUT angle, exactly as the physical scattering operator.
        scatter = op.phase_matrix.to(torch.complex128) * op.weights[None, :]
        return diagonal + self.mean_t[..., None] * eye - self.mean_s[..., None] * scatter

    def homogeneous_matrix(self):
        """Fresh diagnostic H0(B,H,W,L,L); the large matrix is not retained."""
        self.prepare()
        return self._homogeneous_matrix_unchecked()

    def angular_lift(self, value):
        """Q value; used only for the input angular moment space."""
        self._validate_field(value, self.n_modes)
        return self._angular(self.basis, value)

    def restrict(self, value):
        """Q^H value, distinct from the adjoint of the response lift."""
        self._validate_field(value, self.physical.n_angles)
        return self._angular(self.basis.conj().T, value)

    angular_restrict = restrict

    def lift(self, value):
        """Full-angle unshifted homogeneous response U value."""
        self._validate_field(value, self.n_modes)
        return self._spectral(self.response_symbol, value)

    def adjoint(self, value):
        """U^H value under the Euclidean full-field inner product."""
        self._validate_field(value, self.physical.n_angles)
        return self._spectral(self.response_symbol.conj().transpose(-2, -1), value)

    def action(self, value):
        """H U value through the original heterogeneous physical H."""
        # Spatially varying coefficients do not commute with U's convolution.
        return self.physical.A_op(self.lift(value))

    __call__ = action

    def physical_adjoint(self, value):
        """Original stored H^H; output-angle weights follow phase^H."""
        self._validate_field(value, self.physical.n_angles)
        op = self.physical
        phase = op.phase_matrix.to(torch.complex128)
        # H scattering is s * phase * diag(weights). Taking its adjoint
        # first multiplies the spatial coefficient, then phase^H and weights.
        spatial = op.sigma_s.to(torch.complex128) * value
        angular = self._angular(phase.conj().T, spatial)
        scattered = op.weights[None, :, None, None] * angular
        return (-op.streaming_op(value) + op.sigma_t.to(torch.complex128) * value - scattered)

    def adjoint_action(self, value):
        """(H U)^H value = U^H H^H value, with no reduced closure."""
        return self.adjoint(self.physical_adjoint(value))

    def oblique_action(self, value):
        """Q^H H U value; homogeneous limit is Gram value."""
        return self.restrict(self.action(value))

    def oblique_adjoint(self, value):
        """(Q^H H U)^H value = U^H H^H Q value."""
        return self.adjoint_action(self.angular_lift(value))

    def galerkin_action(self, value):
        """U^H H U value; different from the oblique Q^H H U closure."""
        return self.adjoint(self.action(value))

    def homogeneous_action(self, value):
        """H0 value in full-angle space, without an artificial shift."""
        self._validate_field(value, self.physical.n_angles)
        op = self.physical
        weighted = op.weights[None, :, None, None] * value
        scatter = self._angular(op.phase_matrix.to(torch.complex128), weighted)
        return op.streaming_op(value) + self.mean_t.to(torch.complex128) * value - self.mean_s.to(torch.complex128) * scatter

    def solve_qmean(self, value):
        """Alias for H0^-1 Q value; no solve of heterogeneous reduced H."""
        return self.lift(value)

    def reference_response(self, value):
        """H0^-1 QQ^H value, the existing harmonic input-reference control."""
        return self.lift(self.restrict(value))

    def coercivity_margin(self):
        """Per-material min_x(t-s*lambda_max(Herm K)), an FP64 estimate."""
        self.prepare()
        op = self.physical
        scatter = op.phase_matrix.to(torch.complex128) * op.weights[None, :]
        mu = torch.linalg.eigvalsh((scatter + scatter.conj().T) / 2).max()
        return (op.sigma_t - op.sigma_s * mu).flatten(1).amin(1)

    def homogeneous_norm_upper_bound(self):
        """Cheap per-material upper estimate on max_k ||H0(k)||_2."""
        self.prepare()
        op = self.physical
        scatter = op.phase_matrix.to(torch.complex128) * op.weights[None, :]
        scatter_norm = torch.linalg.matrix_norm(scatter, ord=2)
        stream = op._stream_symbol(op.sigma_t.shape[0], torch.complex128, op.sigma_t.device)
        return (stream.abs().flatten(1).amax(1) + self.mean_t.flatten()
                + self.mean_s.flatten().abs() * scatter_norm)

    def image_norm_lower_bound(self):
        """Conservative estimate m*sqrt(lambda_min Gram)/max_k||H0||.

        If the physical accretivity margin m is positive and scattering is
        nonnegative, ||H U c|| >= bound*||c|| in exact arithmetic. The triangle
        upper bound on H0 avoids a full-grid SVD. Returned nonpositive-margin
        cases are zero. This ordinary FP64 evaluation is not directed-rounded
        and gives no corresponding automatic coercivity claim for Q^H H U.
        """
        self.prepare()
        if bool(torch.any(self.physical.sigma_s < 0)):
            raise ValueError("the lower-bound estimate requires nonnegative scattering")
        gram_min = torch.linalg.eigvalsh((self.gram + self.gram.conj().T) / 2).min().clamp_min(0)
        return self.coercivity_margin().clamp_min(0) * gram_min.sqrt() / self.homogeneous_norm_upper_bound()


FullTransportResponseRange = TransportResponseRange
